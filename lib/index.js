"use strict";

/**
 * Representation a of zip file in js
 * @constructor
 */
function JSZip() {
    // if this constructor is used without `new`, it adds `new` before itself:
    if(!(this instanceof JSZip)) {
        return new JSZip();
    }

    if(arguments.length) {
        throw new Error("The constructor with parameters has been removed in JSZip 3.0, please check the upgrade guide.");
    }

    // object containing the files :
    // {
    //   "folder/" : {...},
    //   "folder/data.txt" : {...}
    // }
    // NOTE: we use a null prototype because we do not
    // want filenames like "toString" coming from a zip file
    // to overwrite methods and attributes in a normal Object.
    this.files = Object.create(null);

    this.comment = null;

    // Where we are in the hierarchy
    this.root = "";
    this.clone = function() {
        var newObj = new JSZip();
        for (var i in this) {
            if (typeof this[i] !== "function") {
                newObj[i] = this[i];
            }
        }
        // The clone must not share the `files` object with the original:
        // adding or removing a file on one of them would silently alter the
        // other. The entries themselves are shared, they are replaced (not
        // mutated) by the file manipulation methods. folder() re-shares the
        // object explicitly to keep its view on the same archive, see
        // object.js.
        var files = Object.create(null);
        for (var fileName in this.files) {
            if (Object.prototype.hasOwnProperty.call(this.files, fileName)) {
                files[fileName] = this.files[fileName];
            }
        }
        newObj.files = files;
        return newObj;
    };
}
JSZip.prototype = require("./object");
JSZip.prototype.loadAsync = require("./load");
JSZip.support = require("./support");
JSZip.defaults = require("./defaults");

